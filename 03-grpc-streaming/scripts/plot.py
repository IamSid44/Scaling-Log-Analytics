#!/usr/bin/env python3
"""results/benchmark.csv -> results/summary.md + results/*.png

    python3 scripts/plot.py

One section and one figure per experiment (the `exp` column written by
slurm/benchmark.slurm): workers, wire, distribution, batch, queries, latency,
size, and the 10,000-record-message sweeps workers_b10k, distribution_b10k.
Medians over repetitions; the figures also show every repetition. Rows whose
`correct` column is not 1 are discarded, loudly. summary.md is written even
without matplotlib.

"Cores busy" = a component's CPU seconds during the stream / the stream's wall
time (cpu_* columns). A Python process whose own code is the bottleneck sits
near 1.0 (the GIL runs Python code on one core at a time).
"""

import csv
import os
import statistics
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "results")
BLUE, ORANGE, AQUA, YELLOW, VIOLET = "#2a78d6", "#eb6834", "#1baf7a", "#eda100", "#4a3aa7"
INK, INK2, GRID, GRAY = "#0b0b0b", "#52514e", "#e1e0d9", "#898781"

path = os.path.join(RES, "benchmark.csv")
if not os.path.exists(path):
    sys.exit("error: no results/benchmark.csv")
rows = list(csv.DictReader(open(path, newline="")))
bad = [r for r in rows if r.get("correct") != "1"]
rows = [r for r in rows if r.get("correct") == "1"]
if bad:
    print("WARNING: discarded %d row(s) whose final report did not match the reference"
          % len(bad), file=sys.stderr)


def num(r, k):
    try:
        return float(r[k])
    except (KeyError, ValueError, TypeError):
        return None


def busy(r, col):
    """Cores a component kept busy during the stream."""
    c, t = num(r, col), num(r, "t_ingest")
    return c / t if c is not None and t else None


def sel(exp, **fixed):
    return [r for r in rows
            if r["exp"] == exp and all(r.get(k) == str(v) for k, v in fixed.items())]


def group(exp, key, val, **fixed):
    """{key(row): [val(row), ...]} over rows of experiment `exp` matching `fixed`."""
    g = {}
    for r in sel(exp, **fixed):
        v = val(r) if callable(val) else num(r, val)
        if v is not None:
            g.setdefault(key(r), []).append(v)
    return g


def med(exp, key, val, **fixed):
    return {k: statistics.median(v) for k, v in group(exp, key, val, **fixed).items()}


W = lambda r: int(r["workers"])
human = lambda n: "%dM" % (n // 10 ** 6) if n >= 10 ** 6 else "%dk" % (n // 1000)
krps = lambda v: ("%.2fM" % (v / 1e6)) if v >= 1e6 else ("%.0fk" % (v / 1e3))
f2 = lambda v: "--" if v is None else "%.2f" % v

out = []
w = out.append


def table(header, body):
    w("| " + " | ".join(header) + " |")
    w("|" + "|".join(["---"] + [":---:"] * (len(header) - 1)) + "|")
    for b in body:
        w("| " + " | ".join(b) + " |")
    w("")


w("# Streaming analytics: measured results")
w("")
w("Generated by `scripts/plot.py` from `benchmark.csv`. Medians over repetitions. Every row "
  "used here produced a final report byte-identical to the sequential C++ reference "
  "(%d rows kept, %d discarded)." % (len(rows), len(bad)))
w("")
w("Placement: the coordinator, the producer and the query clients run on the first node; "
  "each worker runs on its own node. Throughput = records / wall time of the whole "
  "client-streaming RPC, measured by the producer, so it includes every backpressure stall. "
  "*Cores busy* = a process's CPU time during the stream / the stream's wall time; a Python "
  "process that is itself the bottleneck sits near 1.0.")
w("")

# ------------------------------------------------------------ the per-message model
# Each message on the producer's stream costs the producer's own CPU work for it
# plus a fixed latency L, in series (gRPC Python's synchronous stream sends one
# message at a time). Fit L on every run that the stream limits: round-robin,
# raw wire, unthrottled, no queries, workers not saturated.
def msg_ms(r):
    return num(r, "t_ingest") / num(r, "batches") * 1e3


def prod_ms(r):
    return num(r, "cpu_producer") / num(r, "batches") * 1e3


stream_bound = [r for r in rows
                if r["wire"] == "raw" and r["distribution"] == "roundrobin"
                and r["queriers"] == "0" and r["rate"] == "0"
                and num(r, "cpu_producer") is not None
                and (busy(r, "cpu_worker_max") or 1) < 0.95]
L = None
if stream_bound:
    lat = [msg_ms(r) - prod_ms(r) for r in stream_bound]
    L = statistics.median(lat)
    errs = []
    for r in stream_bound:
        b = int(r["batch"])
        pred = b / ((prod_ms(r) + L) / 1e3)
        errs.append(abs(pred / num(r, "throughput_rps") - 1))
    w("## 0. The model behind every throughput number")
    w("")
    w("In every run where the workers are *not* saturated (%d runs: round-robin, raw wire, "
      "no queries, busiest worker < 0.95 cores busy), the time per message on the producer's "
      "stream is the producer's own CPU time per message plus a fixed **L = %.2f ms** "
      "(range %.2f-%.2f ms), for messages of 10 to 1,000 records alike:" %
      (len(stream_bound), L, min(lat), max(lat)))
    w("")
    w("    time per message = producer CPU per message + L        (in series)")
    w("    throughput      = min( W x one worker's rate ,  b / (b x producer CPU per record + L) )")
    w("")
    w("gRPC Python's synchronous client stream sends one message at a time: it pulls the next "
      "message from the producer's generator (the producer's CPU work) only after the previous "
      "send has completed (L). Predicting each of those runs' throughput from its own producer "
      "CPU and the median L: mean error **%.1f%%**, worst %.1f%%." %
      (100 * statistics.mean(errs), 100 * max(errs)))
    w("")

# ---------------------------------------------------------------- workers + wire + dist
sweeps = [  # (exp, label, colour)
    ("workers", "round-robin, 1,000 rec/msg", BLUE),
    ("workers_b10k", "round-robin, 10,000 rec/msg", VIOLET),
    ("distribution", "hash, 1,000 rec/msg", AQUA),
    ("distribution_b10k", "hash, 10,000 rec/msg", YELLOW),
    ("wire", "parsed at producer, 1,000 rec/msg", ORANGE),
]
thr = {e: med(e, W, "throughput_rps") for e, _, _ in sweeps}
thr_all = {e: group(e, W, "throughput_rps") for e, _, _ in sweeps}
bal = {e: med(e, W, "balance_pct") for e in ("distribution", "distribution_b10k")}
cores = {e: {c: med(e, W, lambda r, c=c: busy(r, c))
             for c in ("cpu_producer", "cpu_coord", "cpu_worker_max")}
         for e, _, _ in sweeps}

if thr["workers"]:
    ws = sorted(thr["workers"])
    base = thr["workers"][ws[0]]
    w("## 1. Throughput vs number of workers")
    w("")
    hdr = ["W"]
    for e, lab, _ in sweeps:
        if thr[e]:
            hdr.append(lab)
    body = []
    for x in ws:
        line = [str(x)]
        for e, _, _ in sweeps:
            if thr[e]:
                v = thr[e].get(x)
                lo_hi = thr_all[e].get(x, [])
                line.append("--" if v is None else "%s (%s-%s)" % (
                    krps(v), krps(min(lo_hi)), krps(max(lo_hi))) if len(lo_hi) > 1
                    else krps(v))
        body.append(line)
    table(hdr, body)
    w("Median (min-max over repetitions). Speed-up of round-robin, 1,000 rec/msg: " +
      ", ".join("W=%d %.2fx" % (x, thr["workers"][x] / base) for x in ws) + ".")
    if thr["workers_b10k"]:
        b10 = thr["workers_b10k"]
        b0 = b10[min(b10)]
        w("Round-robin, 10,000 rec/msg: " +
          ", ".join("W=%d %.2fx" % (x, b10[x] / b0) for x in sorted(b10)) + ".")
    w("")
    w("Cores busy (median) -- which component limits each configuration:")
    w("")
    body = []
    for e, lab, _ in sweeps:
        if not thr[e]:
            continue
        for x in sorted(thr[e]):
            c = cores[e]
            body.append([lab, str(x), f2(c["cpu_producer"].get(x)), f2(c["cpu_coord"].get(x)),
                         f2(c["cpu_worker_max"].get(x)),
                         "%.0f%%" % bal[e][x] if e in bal and x in bal[e] else "100%"])
    table(["configuration", "W", "producer", "coordinator", "busiest worker",
           "busiest worker's share of records"], body)
    w("`raw` = workers parse the log lines (the default); `parsed` = the producer parses and "
      "ships structured records; `hash` = records routed by server id instead of round-robin. "
      "Share = the busiest worker's records as a percentage of a fair share (100% = even).")
    w("")

# ---------------------------------------------------------------- batch
bk = lambda r: int(r["batch"])
thr_b = med("batch", bk, "throughput_rps")
if thr_b:
    msg_b = med("batch", bk, msg_ms)
    pm_b = med("batch", bk, prod_ms)
    cb = {c: med("batch", bk, lambda r, c=c: busy(r, c))
          for c in ("cpu_producer", "cpu_coord", "cpu_worker_max")}
    w("## 2. Streaming granularity: records per message (W = 4)")
    w("")
    table(["records / message", "throughput (rec/s)", "time per message (ms)",
           "producer CPU per message (ms)", "remaining fixed part (ms)",
           "cores busy: producer / coordinator / busiest worker"],
          [[str(b), krps(thr_b[b]), "%.3f" % msg_b[b], "%.3f" % pm_b[b],
            "%.3f" % (msg_b[b] - pm_b[b]),
            "%s / %s / %s" % (f2(cb["cpu_producer"][b]), f2(cb["cpu_coord"][b]),
                              f2(cb["cpu_worker_max"][b]))] for b in sorted(thr_b)])

# ---------------------------------------------------------------- queries
qk = lambda r: int(r["queriers"])
thr_q = med("queries", qk, "throughput_rps")
p50_q = med("queries", qk, "q_p50_ms")
p95_q = med("queries", qk, "q_p95_ms")
co_q = med("queries", qk, lambda r: busy(r, "cpu_coord"))
if thr_q:
    w("## 3. Concurrent queries during ingestion (W = 4)")
    w("")
    table(["query clients", "throughput (rec/s)", "query p50 (ms)", "query p95 (ms)",
           "coordinator cores busy"],
          [[str(q), krps(thr_q[q]), "%.1f" % p50_q[q] if q in p50_q else "--",
            "%.1f" % p95_q[q] if q in p95_q else "--", f2(co_q.get(q))] for q in sorted(thr_q)])

# ---------------------------------------------------------------- latency vs W
p50_w = med("latency", W, "q_p50_ms")
p95_w = med("latency", W, "q_p95_ms")
co_w = med("latency", W, lambda r: busy(r, "cpu_coord"))
thr_w = med("latency", W, "throughput_rps")
if p50_w:
    xs = sorted(p50_w)
    slope = None
    if len(xs) > 1:
        mx, my = statistics.mean(xs), statistics.mean(p50_w[x] for x in xs)
        slope = (sum((x - mx) * (p50_w[x] - my) for x in xs) /
                 sum((x - mx) ** 2 for x in xs))
    w("## 4. Query latency vs number of workers (ingestion held at 150k rec/s)")
    w("")
    table(["W", "ingestion (rec/s)", "query p50 (ms)", "query p95 (ms)",
           "coordinator cores busy"],
          [[str(x), krps(thr_w[x]), "%.1f" % p50_w[x], "%.1f" % p95_w.get(x, 0),
            f2(co_w.get(x))] for x in xs])
    if slope is not None:
        w("Least-squares slope of p50: **%.1f ms per additional worker** (one more partial "
          "state of ~2,000 entries for the coordinator to decode and merge)." % slope)
        w("")

# ---------------------------------------------------------------- size
nk = lambda r: int(r["n"])
thr_n = med("size", nk, "throughput_rps")
t_n = med("size", nk, "t_ingest")
if thr_n:
    w("## 5. Input size (W = 4)")
    w("")
    table(["N", "throughput (rec/s)", "time (s)"],
          [[human(n), krps(thr_n[n]), "%.2f" % t_n[n]] for n in sorted(thr_n)])

open(os.path.join(RES, "summary.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
print("wrote results/summary.md")

# ---------------------------------------------------------------- plots
try:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
except ImportError:
    print("matplotlib missing -- skipped the plots")
    sys.exit(0)

plt.rcParams.update({"font.size": 9, "axes.edgecolor": GRAY, "axes.labelcolor": INK2,
                     "xtick.color": INK2, "ytick.color": INK2, "axes.titlecolor": INK,
                     "axes.titlesize": 10, "axes.titlelocation": "left",
                     "legend.frameon": False})
LINE = dict(linewidth=2, marker="o", markersize=5)


def style(ax, xl, yl, title):
    ax.set_title(title, pad=8)
    ax.set_xlabel(xl)
    ax.set_ylabel(yl)
    ax.grid(True, color=GRID, linewidth=0.8)
    ax.set_axisbelow(True)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)


def save(fig, name):
    fig.tight_layout()
    fig.savefig(os.path.join(RES, name), dpi=150, bbox_inches="tight")
    plt.close(fig)
    print("wrote results/" + name)


def reps(ax, g, colour, scale=1e3):
    for x, vs in g.items():
        ax.scatter([x] * len(vs), [v / scale for v in vs], s=12, color=colour, alpha=0.35,
                   linewidths=0, zorder=3)


if thr["workers"]:
    ws = sorted(thr["workers"])
    fig, (a1, a2, a3) = plt.subplots(1, 3, figsize=(13.5, 4.0),
                                     gridspec_kw={"width_ratios": [1.35, 1, 1]})
    # one worker's rate: from the 10,000-record sweep if present (worker-bound at every W)
    r1 = (thr["workers_b10k"] or thr["workers"])[ws[0]]
    a1.plot(ws, [r1 * x / 1e3 for x in ws], color=GRAY, linestyle=":", linewidth=1.2,
            label="W x one worker")
    sb = [r for r in stream_bound if r["batch"] == "1000"]
    if L is not None and sb:
        cmin = min(prod_ms(r) for r in sb)
        cmax = max(prod_ms(r) for r in sb)
        a1.axhspan(1000 / (cmax + L), 1000 / (cmin + L), color=BLUE, alpha=0.08, linewidth=0,
                   label="stream ceiling, 1,000 rec/msg (model)")
    for e, lab, col in sweeps:
        if thr[e]:
            xs = sorted(thr[e])
            a1.plot(xs, [thr[e][x] / 1e3 for x in xs], color=col, label=lab, **LINE)
            reps(a1, thr_all[e], col)
    a1.set_ylim(bottom=0)
    a1.set_xticks(ws)
    style(a1, "workers W", "throughput (thousand records/s)", "Throughput vs workers")
    a1.legend(fontsize=7.5, loc="upper left")

    c = cores["workers"]
    for col_name, lab, colour in (("cpu_worker_max", "busiest worker", BLUE),
                                  ("cpu_producer", "producer", ORANGE),
                                  ("cpu_coord", "coordinator", VIOLET)):
        xs = sorted(c[col_name])
        a2.plot(xs, [c[col_name][x] for x in xs], color=colour, label=lab, **LINE)
    if cores["workers_b10k"]["cpu_worker_max"]:
        cb10 = cores["workers_b10k"]["cpu_worker_max"]
        xs = sorted(cb10)
        a2.plot(xs, [cb10[x] for x in xs], color=BLUE, linestyle="--", linewidth=1.5,
                marker="s", markersize=4, label="busiest worker, 10,000 rec/msg")
    a2.axhline(1.0, color=GRAY, linewidth=0.8, linestyle=":")
    a2.set_ylim(0, 1.45)
    a2.set_xticks(ws)
    style(a2, "workers W", "cores busy (CPU s / wall s)",
          "Where the time goes (round-robin)")
    a2.legend(fontsize=7.5, loc="upper right")

    if bal["distribution"]:
        hs = sorted(bal["distribution"])
        a3.plot(ws, [100] * len(ws), color=BLUE, label="round-robin", **LINE)
        a3.plot(hs, [bal["distribution"][x] for x in hs], color=AQUA, label="hash", **LINE)
        a3.set_xticks(ws)
        a3.set_ylim(bottom=0)
        style(a3, "workers W", "busiest worker, % of a fair share",
              "Load balance (Zipf-skewed servers)")
        a3.legend(fontsize=8, loc="upper left")
    else:
        a3.axis("off")
    save(fig, "throughput_vs_workers.png")

if thr_b:
    bs = sorted(thr_b)
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(9.5, 3.6))
    a1.plot(bs, [thr_b[b] / 1e3 for b in bs], color=BLUE, label="measured", **LINE)
    reps(a1, group("batch", bk, "throughput_rps"), BLUE)
    if L is not None:
        a1.plot(bs, [b / ((pm_b[b] + L) / 1e3) / 1e3 for b in bs], color=GRAY, linestyle="--",
                linewidth=1.2, label="stream model b / (producer CPU + L)")
        r1 =thr["workers"][min(thr["workers"])] if thr["workers"] else None
        if r1:
            a1.axhline(4 * r1 / 1e3, color=GRAY, linestyle=":", linewidth=1.2,
                       label="4 x one worker")
    a1.set_xscale("log")
    a1.set_xticks(bs)
    a1.set_xticklabels([str(b) for b in bs])
    a1.set_ylim(bottom=0)
    style(a1, "records per message (log scale)", "throughput (thousand records/s)",
          "Streaming granularity (W = 4)")
    a1.legend(fontsize=7.5, loc="upper left")
    a2.bar(range(len(bs)), [pm_b[b] for b in bs], color=ORANGE, label="producer CPU")
    a2.bar(range(len(bs)), [msg_b[b] - pm_b[b] for b in bs], bottom=[pm_b[b] for b in bs],
           color=GRAY, alpha=0.6, label="producer waiting (L = %.2f ms while the stream "
           "limits; more once the workers do)" % (L or 0))
    a2.set_xticks(range(len(bs)))
    a2.set_xticklabels([str(b) for b in bs])
    style(a2, "records per message", "ms per message", "Time per message")
    a2.legend(fontsize=7.5, loc="upper left")
    save(fig, "batch_size.png")

if thr_q:
    qs = sorted(thr_q)
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(9.0, 3.6))
    a1.plot(qs, [thr_q[q] / 1e3 for q in qs], color=BLUE, label="throughput", **LINE)
    reps(a1, group("queries", qk, "throughput_rps"), BLUE)
    a1.set_ylim(bottom=0)
    a1.set_xticks(qs)
    style(a1, "concurrent query clients", "throughput (thousand records/s)",
          "Ingestion while being queried (W = 4)")
    ax2 = a1.twinx()
    ax2.plot(qs, [co_q[q] for q in qs], color=VIOLET, linestyle="--", linewidth=1.5,
             marker="s", markersize=4, label="coordinator cores busy")
    ax2.set_ylim(0, 1.2)
    ax2.set_ylabel("coordinator cores busy", color=VIOLET)
    ax2.spines["top"].set_visible(False)
    h1, l1 = a1.get_legend_handles_labels()
    h2, l2 = ax2.get_legend_handles_labels()
    a1.legend(h1 + h2, l1 + l2, fontsize=7.5, loc="lower left")
    q2 = [q for q in qs if q in p50_q]
    a2.plot(q2, [p50_q[q] for q in q2], color=BLUE, label="p50", **LINE)
    a2.plot(q2, [p95_q[q] for q in q2], color=VIOLET, label="p95", **LINE)
    a2.set_ylim(bottom=0)
    a2.set_xticks(qs)
    style(a2, "concurrent query clients", "query latency (ms)", "Query latency")
    a2.legend(fontsize=8)
    save(fig, "queries.png")

if p50_w:
    ws = sorted(p50_w)
    fig, ax = plt.subplots(figsize=(5.6, 3.6))
    ax.plot(ws, [p50_w[x] for x in ws], color=BLUE, label="query p50", **LINE)
    ax.plot(ws, [p95_w[x] for x in ws], color=VIOLET, label="query p95", **LINE)
    if slope is not None:
        mx, my = statistics.mean(ws), statistics.mean(p50_w[x] for x in ws)
        ax.plot(ws, [my + slope * (x - mx) for x in ws], color=GRAY, linestyle=":",
                linewidth=1.2, label="fit: %.1f ms per worker" % slope)
    ax.set_ylim(bottom=0)
    ax.set_xticks(ws)
    style(ax, "workers W", "latency (ms)", "Query latency vs workers (150k rec/s)")
    ax.legend(fontsize=8)
    save(fig, "latency_vs_workers.png")

if thr_n:
    ns = sorted(thr_n)
    fig, (a1, a2) = plt.subplots(1, 2, figsize=(9.0, 3.4))
    a1.plot([n / 1e6 for n in ns], [thr_n[n] / 1e3 for n in ns], color=BLUE, **LINE)
    a1.set_ylim(bottom=0)
    style(a1, "records (millions)", "throughput (thousand records/s)",
          "Throughput vs input size (W = 4)")
    a2.plot([n / 1e6 for n in ns], [t_n[n] for n in ns], color=BLUE, **LINE)
    a2.set_ylim(bottom=0)
    style(a2, "records (millions)", "time (s)", "End-to-end time vs input size")
    save(fig, "size.png")
